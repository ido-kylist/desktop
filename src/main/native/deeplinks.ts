/**
 * `cleon://` deep links: two arrival paths, one parser, one delivery path.
 *
 * A deep link is untrusted input from outside the app, so it is turned into a
 * `DeepLinkTarget` by a Zod schema before anything acts on it. The renderer only
 * ever receives the parsed target — it never sees a raw URL and never has to trust
 * one — and an id that is not a uuid is dropped here, where the cost is a log line,
 * rather than becoming a failed lookup after the window has already been focused.
 *
 * Where the links come from:
 *  - macOS delivers them through `app.on("open-url")`, sometimes during launch.
 *  - Windows and Linux pass the URL in the argv of the `second-instance` event that
 *    the single-instance lock in `handlers.ts` turns on.
 *
 * This module imports `electron` for types only and `channels.ts` relatively, so the
 * two parsers can be exercised from a plain Node process — see
 * `tests/unit/deep-link.spec.ts`. (Vitest's config declares no `@shared` alias, so a
 * runtime aliased import here would not resolve in that test.)
 */

import type { App, Event } from "electron";
import { z } from "zod";
import { DEEP_LINK_CHANNEL } from "../../shared/channels.js";

/** The scheme and the one host this build answers to. */
export const DEEP_LINK_SCHEME = "cleon";
export const THREAD_DEEP_LINK_HOST = "thread";

/**
 * The parsed form, and the whole of it: `cleon://thread/<uuid>`.
 *
 * Schema first so the type cannot drift from the boundary it describes, and so a
 * future contract bump can adopt this declaration verbatim. D5's contract half is
 * frozen, so the renderer-side type is declared alongside the preload bridge rather
 * than in `src/shared`.
 */
export const DeepLinkTargetSchema = z.object({
  kind: z.literal("thread"),
  threadId: z.uuid(),
});
export type DeepLinkTarget = z.infer<typeof DeepLinkTargetSchema>;

/**
 * `cleon://thread/<uuid>` → a target. Anything else → `null`.
 *
 * Deliberately tolerated: a trailing slash, and an upper-case uuid. Both are
 * unambiguous, and both arrive in practice — links get typed by hand, pasted out
 * of logs, and generated by other apps. The id is lower-cased on the way in because
 * the database's ids are lower-case, so the same thread is not "not found" because
 * of a shift key.
 *
 * Deliberately refused: any other scheme or host (not this app's link), any other
 * path shape, and anything that is not a uuid.
 */
export function parseDeepLink(raw: string): DeepLinkTarget | null {
  if (raw.length === 0) return null;

  let url: URL;
  try {
    url = new URL(raw);
  } catch {
    // Not a URL at all: the argv[0] binary path, a flag, a stray word.
    return null;
  }

  // `URL` lower-cases the scheme and the host for us, so an upper-case link that a
  // mail client capitalised still matches.
  if (url.protocol !== `${DEEP_LINK_SCHEME}:`) return null;
  if (url.host !== THREAD_DEEP_LINK_HOST) return null;

  // `/` and `/<uuid>/` both collapse to a single non-empty segment; a missing id,
  // a nested path, or anything longer is refused.
  const segments = url.pathname.split("/").filter((part) => part.length > 0);
  if (segments.length !== 1) return null;

  const parsed = DeepLinkTargetSchema.safeParse({
    kind: "thread",
    threadId: (segments[0] ?? "").toLowerCase(),
  });
  return parsed.success ? parsed.data : null;
}

/**
 * The argv form: `["Electron", "app", "cleon://thread/<uuid>"]`.
 *
 * On Windows and Linux the URL arrives as one argument among the binary path and
 * whatever flags the OS passed, in an order nobody promises, so every argument is
 * offered to the same parser and the first hit wins. The binary path and the flags
 * are not `cleon://` links, so they fail on their own.
 */
export function parseDeepLinkFromArgv(argv: readonly string[]): DeepLinkTarget | null {
  for (const argument of argv) {
    const target = parseDeepLink(argument);
    if (target !== null) return target;
  }
  return null;
}

/**
 * The slice of a `BrowserWindow` this module needs.
 *
 * Structural rather than the class, so the shape delivery depends on is stated here
 * and a real `BrowserWindow` satisfies it without a cast.
 */
export interface DeepLinkWindow {
  isDestroyed(): boolean;
  isMinimized(): boolean;
  restore(): void;
  show(): void;
  focus(): void;
  readonly webContents: { send(channel: string, payload: unknown): void };
}

export interface DeepLinkDeps {
  /** The `app` module. Listeners in, nothing else. */
  readonly app: Pick<App, "on" | "off">;
  /**
   * The window a link should land in — the focused one when there is one, otherwise
   * the newest live window. `null` means the app has no window yet.
   */
  readonly windowFor: () => DeepLinkWindow | null;
}

export interface DeepLinkRegistration {
  /** Detaches both listeners. Called on `will-quit`. */
  dispose(): void;
}

/**
 * Registers both arrival paths. Call it before `ready`: macOS can deliver
 * `open-url` while the app is still launching.
 *
 * A link that arrives before any window exists is logged and dropped rather than
 * queued. Queueing it correctly needs a flush on the main window's first paint (or a
 * renderer-ready handshake), and both live in `src/main/index.ts`, which this slice
 * does not own — see the handoff note. A link queued into a window whose preload has
 * not subscribed yet would be lost silently, which is worse than a logged drop.
 */
export function registerDeepLinks(deps: DeepLinkDeps): DeepLinkRegistration {
  const deliver = (target: DeepLinkTarget): void => {
    const window = deps.windowFor();
    if (window === null || window.isDestroyed()) {
      console.warn("[native] deep link dropped: no window is open to receive it", target.threadId);
      return;
    }

    // A minimised window would be handed the event while showing nothing, and a
    // hidden one would never come forward on its own.
    if (window.isMinimized()) window.restore();
    window.show();
    window.focus();
    window.webContents.send(DEEP_LINK_CHANNEL, target);
  };

  const onOpenUrl = (event: Event, url: string): void => {
    // macOS hands the URL to the app; nothing else should act on it.
    event.preventDefault();

    const target = parseDeepLink(url);
    if (target === null) {
      console.warn("[native] ignored deep link: not a cleon://thread/<uuid> link", url);
      return;
    }
    deliver(target);
  };

  const onSecondInstance = (_event: Event, argv: string[]): void => {
    const target = parseDeepLinkFromArgv(argv);
    // A second launch carrying no link is just "the user opened the app again".
    if (target === null) return;
    deliver(target);
  };

  deps.app.on("open-url", onOpenUrl);
  deps.app.on("second-instance", onSecondInstance);

  return {
    dispose() {
      deps.app.off("open-url", onOpenUrl);
      deps.app.off("second-instance", onSecondInstance);
    },
  };
}
